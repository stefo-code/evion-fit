export type Equipment = "körpergewicht" | "kurzhantel" | "langhantel" | "maschine" | "kabel" | "band";

/** Körperliche Einschränkungen aus dem Profil (harte Filter im Generator). */
export type Einschraenkung = "schulter" | "ruecken" | "knie" | "huefte" | "herz";

export type LibUebung = {
  id: string;
  name: string;
  muskel: string;
  muster: Muster;
  equipment: Equipment[];
  /** Grundübung mit hohem Reiz (bleibt bei Zeitmangel im Plan). Isolation = false. */
  grund: boolean;
  zielSaetze: number;
  wdhBereich: string;
  startGewicht: number;
  hinweis: string;
  /** Belastet die Wirbelsäule kaum (axial gering) → rückenschonend. */
  rueckenschonend: boolean;
  /** Geeignet für Rückbildung nach der Schwangerschaft (kein Druck auf Beckenboden/Rektusdiastase). */
  rueckbildung: boolean;
  /** Für Einsteiger geeignet. */
  einsteiger: boolean;
  /** Platzhalterbild nach Bewegungsmuster statt Foto. */
  bildMuster?: boolean;
  /** Bei diesen Einschränkungen HART ausschließen (z. B. keine Nacken-Varianten bei Schulter). */
  meidetBei?: Einschraenkung[];
  /** Bei diesen Einschränkungen bevorzugt auswählen (gelenkschonende Alternative). */
  bevorzugtBei?: Einschraenkung[];
};

/** Normalisiert die Freitext-/Checkbox-Einschränkungen aus dem Profil zu Tags. */
export function einschraenkungTags(liste: string[] | null | undefined): Einschraenkung[] {
  const tags = new Set<Einschraenkung>();
  for (const roh of liste ?? []) {
    const l = roh.toLowerCase();
    if (l.includes("schulter")) tags.add("schulter");
    if (l.includes("rücken") || l.includes("ruecken")) tags.add("ruecken");
    if (l.includes("knie")) tags.add("knie");
    if (l.includes("hüfte") || l.includes("huefte")) tags.add("huefte");
    if (l.includes("herz") || l.includes("kreislauf")) tags.add("herz");
  }
  return [...tags];
}

