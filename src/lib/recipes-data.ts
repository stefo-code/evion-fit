const kuechenLabel: Record<Kueche, string> = {
  mediterran: "Mediterran",
  asiatisch: "Asiatisch",
  mexikanisch: "Mexikanisch",
  orientalisch: "Orientalisch",
  indisch: "Indisch",
  "schweizerisch-deutsch": "Schweizerisch-deutsch",
};

const zahl = (n: number) => n.toLocaleString("de-DE");

function zutatText([key, menge, text]: Z): string {
  if (text) return text;
  return `${zahl(menge)} ${L(key).ml ? "ml" : "g"} ${L(key).name}`;
}

export type Naehrwerte = { kcal: number; protein: number; kh: number; fett: number };

/** Summe der Nährwerte aller Zutaten geteilt durch die Portionen (ungerundet). */
export function naehrwerteJePortion(zutaten: Z[], portionen: number): Naehrwerte {
  const s = { kcal: 0, protein: 0, kh: 0, fett: 0 };
  for (const [key, menge] of zutaten) {
    const l = L(key);
    const f = menge / 100;
    s.kcal += l.kcal * f;
    s.protein += l.p * f;
    s.kh += l.kh * f;
    s.fett += l.f * f;
  }
  return {
    kcal: s.kcal / portionen,
    protein: s.protein / portionen,
    kh: s.kh / portionen,
    fett: s.fett / portionen,
  };
}

function baueRezept(d: RezeptDef): Rezept {
  const portionen = d.portionen ?? 1;
  const roh = naehrwerteJePortion(d.z, portionen);
  const kcal = Math.round(roh.kcal);
  const protein = Math.round(roh.protein);
  const kh = Math.round(roh.kh);
  const fett = Math.round(roh.fett);

  const herkunft = new Set(d.z.map(([k]) => L(k).t).filter(Boolean));
  const vegetarisch =
    !herkunft.has("fleisch") && !herkunft.has("fisch") && !herkunft.has("meeresfruechte");
  const vegan =
    vegetarisch && !herkunft.has("milch") && !herkunft.has("ei") && !herkunft.has("honig");
  const pescetarisch = !vegetarisch && !herkunft.has("fleisch");

  const allergene = new Set<Allergen>();
  for (const [k] of d.z) for (const a of L(k).a ?? []) allergene.add(a);

  const mealPrep = !!d.mealPrep;
  const budget = !!d.budget;
  const tags = [
    d.mahlzeit,
    kuechenLabel[d.kueche],
    ...(vegan ? ["Vegan"] : vegetarisch ? ["Vegetarisch"] : pescetarisch ? ["Pescetarisch"] : []),
    ...(protein >= 40 ? ["High Protein"] : []),
    ...(mealPrep ? ["Meal Prep"] : []),
    ...(budget ? ["Günstig"] : []),
    ...(d.tags ?? []),
  ];

  return {
    id: d.id,
    name: d.name,
    zeit: d.zeit,
    portionen,
    kcal,
    protein,
    kh,
    fett,
    tags,
    vegetarisch,
    vegan,
    pescetarisch,
    mahlzeit: d.mahlzeit,
    kueche: d.kueche,
    allergene: [...allergene],
    mealPrep,
    budget,
    zielEignung: zielEignungAusMakros(kcal, protein),
    zutaten: d.z.map((zt) => ({
      text: zutatText(zt),
      key: L(zt[0]).vorrat,
      basis: !!L(zt[0]).basis,
    })),
    schritte: d.schritte,
  };
}

/** Die ausformulierten Rezepte – Nährwerte & Etiketten aus den Zutaten berechnet. */
export const rezepteDatenbank: Rezept[] = defs.map(baueRezept);

