// ---------------------------------------------------------------------------
// Kalorienbänder je Ziel (pro Portion) – gemeinsam für alle Rezepte genutzt
// ---------------------------------------------------------------------------

export type ZielBand = { ziel: ZielEignung; min: number; max: number; minProtein: number };

export const zielBaender: ZielBand[] = [
  { ziel: "fettabbau", min: 300, max: 550, minProtein: 30 },
  { ziel: "recomp", min: 450, max: 700, minProtein: 35 },
  { ziel: "muskelaufbau", min: 600, max: 900, minProtein: 40 },
];

/**
 * Ordnet ein Rezept den Zielen zu, deren Kalorienband es trifft. Bevorzugt
 * werden Bänder, deren Mindestprotein ebenfalls erreicht wird; sonst zählt das
 * Kalorienband allein. Liegt ein Rezept in keinem Band, bleibt die Liste leer.
 */
export function zielEignungAusMakros(kcal: number, protein: number): ZielEignung[] {
  const imBand = zielBaender.filter((b) => kcal >= b.min && kcal <= b.max);
  const mitProtein = imBand.filter((b) => protein >= b.minProtein);
  return (mitProtein.length ? mitProtein : imBand).map((b) => b.ziel);
}

